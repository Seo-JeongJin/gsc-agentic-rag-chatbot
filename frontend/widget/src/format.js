/**
 * 챗봇 답변을 말풍선에 넣을 HTML로 바꿈 (2026-11-09 브라우저 화면 확인 + 사용자 요청 시안 B).
 *
 * 왜:
 * - 모델이 강조하려고 "**입도선매전형**"처럼 마크다운 굵게를 자주 씀(하루 답변 242개 중 41개) — 예전엔 답을 textContent로
 *   그대로 넣어서 ** 기호가 지원자 눈에 그대로 보였음.
 * - 한 문단에 문장이 3~4개씩 이어져 좁은 말풍선에서 글이 덩어리로 보였음. 모델에게 "줄을 나눠 쓰라"고 프롬프트로 시키는 건
 *   실험에서 정답을 흔들어서(인턴십 질문 2/2 "확인해드리기 어렵습니다") 접고, 보여줄 때 코드가 문장 끝에서 줄을 바꿈.
 *   DB에 저장되는 답·LLM은 그대로 — 화면 표시만 바뀜.
 *
 * 순서가 핵심: ① HTML 특수문자를 전부 글자로 바꿈(escape — 예전 textContent와 같은 XSS 방어) → ② **굵게** → ③ 문장 끝 줄바꿈
 *   → ④ 빈 줄 기준 <p> 문단. escape를 맨 먼저 해야 답에 섞인 태그가 살아나지 않음. 굵게를 줄바꿈보다 먼저 하는 이유:
 *   굵게 규칙은 줄을 넘지 못하므로, 굵은 구간 안에서 줄을 먼저 바꾸면 굵게가 깨짐.
 * 마크다운 라이브러리를 안 쓰는 이유: 위젯은 남의 홈페이지에 붙는 코드라 가벼워야 하고, 실제로 필요한 건 굵게뿐.
 * 문단 안의 줄바꿈("- 목록" 등)은 말풍선 CSS(white-space:pre-wrap)가 그대로 줄을 바꿔 보여줌.
 */

const HTML_ESCAPES = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };

// 문장 끝: "한글 글자 + . ! ?" 뒤에 공백, 그 다음이 글자·숫자·괄호·따옴표·태그(<strong>)·escape된 문자(&)로 시작할 때.
// 앞 글자를 한글로 제한해서 "1.0–5.9등급", "2027. 2. 10." 같은 숫자 속 점은 안 건드림.
// 다음 글자 조건 때문에 "주세요. 😊"처럼 문장 뒤 이모지는 앞 문장에 붙어 있음(이모지만 따로 한 줄이면 어색함).
const SENTENCE_END = /([가-힣][.!?])[ ]+(?=[가-힣A-Za-z0-9(<&"'“‘])/g;

/** HTML 특수문자 5개를 글자로 바꿈 — 브라우저가 태그로 해석하지 못하게. */
function escapeHtml(text) {
  return text.replace(/[&<>"']/g, (ch) => HTML_ESCAPES[ch]);
}

/** 문단 하나: 굵게(같은 줄 안에서 짝이 맞는 **…**만) → 문장 끝 줄바꿈. */
function formatParagraph(paragraph) {
  return paragraph
    .replace(/\*\*([^*\n]+?)\*\*/g, "<strong>$1</strong>")
    .replace(SENTENCE_END, "$1\n");
}

/** 답변 텍스트 → 말풍선 innerHTML. 빈 줄(공백만 있는 줄 포함)로 나뉜 문단마다 <p> — 문단 사이 간격은 CSS가 줌. */
export function formatAnswer(text) {
  return escapeHtml(text.trim())
    .split(/\n\s*\n/)
    .map((paragraph) => `<p>${formatParagraph(paragraph.trim())}</p>`)
    .join("");
}
